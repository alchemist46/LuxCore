"""Generates the boundary table of the subsurface random walk, the block
between the GENERATED markers of include/slg/materials/subsurface_funcs.cl.

The color of the walk (subsurface.color of openpbr, color of the subsurface
material) is the multiple-scattering albedo: the fraction of the light that
enters a semi-infinite slab of the medium and comes out again (the OpenPBR
specification). The van de Hulst mapping SSS_SingleScatteringAlbedo() gives
the single-scattering albedo of that color for an index-matched boundary. The
walk reflects at the boundary of relative IOR eta > 1 (SSSWalk_InternalReflection():
the internal Fresnel reflectance, total beyond the critical angle), which
sends most of the light back into the medium for another walk, so the slab
with the van de Hulst albedo of C returns far less than C (0.28 for C = 0.5
at eta 1.5).

The table gives the color c' to walk with, so that the slab with the boundary
returns what the index-matched slab returns for C (the van de Hulst mapping
keeps its own error, about 1%, at every eta). It stores the effective
transmittance T of the boundary, defined by

    c' = C / (T + C (1 - T))

(the albedo of a walk that leaves with the probability T at each arrival at
the boundary and returns with C' otherwise), which is smooth in C and eta and
exactly 1 at eta = 1, where c' is C.

The returns are those of an analog walk in a semi-infinite slab of isotropic
scattering, sigma_t = 1 (only the depth and the cosine to the normal matter):
the entry direction cosine-distributed into the medium (the walk's entry
lobe), exponential free flights, the reflection with the smooth Fresnel of
SSS_InternalFresnel() and the fresh free flight from the boundary after it.
Each walk records the number n of its scattering events until it leaves, and
the return of the single-scattering albedo alpha is E[alpha^n] (with the
throughput factor alpha / 0.2 below the minimum albedo 0.2 of SSSWalk_Init()).
The walks still inside after MAX_SCATTER events (SSS_MAX_BOUNCES) count as
absorbed, as in the renderer. T is fitted up to C = C_MAX_FIT and held
constant above it (see main()). The
anisotropic walks use the same table (their boundary loss is close to the
isotropic one after the first few events).

Grids: C uniform in [0, 1] (N_C points), eta uniform in
sqrt((eta - 1) / (ETA_MAX - 1)) (N_ETA points), as the GGX energy tables;
linear interpolation, eta clamped to [1, ETA_MAX].

Run it from the source tree root (a few minutes, numpy only):

    python3 build-system/tools/subsurface_boundary_table.py
"""

import math
import os
import re
import sys
import numpy as np

N_C = 33
N_ETA = 16
ETA_MAX = 3.0
WALKS = 500000
MAX_SCATTER = 65536
MIN_ALPHA = 0.2
C_MAX_FIT = 0.9
SEED = 1

OUTPUT = os.path.join("include", "slg", "materials", "subsurface_funcs.cl")
BEGIN = "// BEGIN GENERATED by build-system/tools/subsurface_boundary_table.py, do not edit."
END = "// END GENERATED"


def internal_fresnel(cos_i, eta):
    """SSS_InternalFresnel() of subsurface_funcs.cl."""
    sin_t2 = eta * eta * np.maximum(0.0, 1.0 - cos_i * cos_i)
    tir = sin_t2 >= 1.0
    cos_t = np.sqrt(np.maximum(0.0, 1.0 - sin_t2))
    rs = (eta * cos_i - cos_t) / (eta * cos_i + cos_t)
    rp = (cos_i - eta * cos_t) / (cos_i + eta * cos_t)
    return np.where(tir, 1.0, 0.5 * (rs * rs + rp * rp))


def single_scattering_albedo(c):
    """SSS_SingleScatteringAlbedo() of subsurface_funcs.cl with g = 0."""
    c = np.clip(c, 0.0, 1.0)
    s = 4.20863 * c - np.sqrt(9.59217 + 41.6808 * c + 17.7126 * c * c) + 4.09712
    return np.clip(1.0 - s * s, 0.0, 0.999999)


def scatter_counts(eta, rng):
    """The number of scattering events of each walk until it leaves the slab
    (MAX_SCATTER + 1 for the walks still inside)."""
    n_out = np.full(WALKS, MAX_SCATTER + 1, np.int64)
    idx = np.arange(WALKS)
    # Depth below the surface (z >= 0) and the cosine of the direction to the
    # inward normal: cosine-distributed entry
    z = np.zeros(WALKS)
    w = np.sqrt(rng.random(WALKS))
    n = np.zeros(WALKS, np.int64)
    while idx.size > 0:
        t = -np.log1p(-rng.random(idx.size))
        znew = z + t * w
        out = znew < 0.0
        if np.any(out):
            leave = out.copy()
            if eta > 1.0:
                refl = rng.random(int(out.sum())) < internal_fresnel(-w[out], eta)
                o = np.flatnonzero(out)
                leave[o[refl]] = False
                # Reflected at the surface: a fresh free flight from it
                z[o[refl]] = 0.0
                w[o[refl]] = -w[o[refl]]
            n_out[idx[leave]] = n[leave]
        inside = ~out
        z[inside] = znew[inside]
        w[inside] = 1.0 - 2.0 * rng.random(int(inside.sum()))
        n[inside] += 1
        keep = ~leave if np.any(out) else np.ones(idx.size, bool)
        keep &= n <= MAX_SCATTER
        idx, z, w, n = idx[keep], z[keep], w[keep], n[keep]
    return n_out


def returns(counts, colors):
    """The return of the walk of each color, from the scatter counts."""
    hist = np.bincount(np.minimum(counts, MAX_SCATTER + 1), minlength=MAX_SCATTER + 2)[:MAX_SCATTER + 1]
    k = np.arange(MAX_SCATTER + 1)
    res = []
    for c in colors:
        a = float(single_scattering_albedo(c))
        weight = 1.0
        if a < MIN_ALPHA:
            weight = a / MIN_ALPHA
            a = MIN_ALPHA
        res.append(weight * float(np.sum(hist * np.power(a, k))) / counts.size)
    return np.array(res)


def main():
    rng = np.random.default_rng(SEED)
    # A fine color grid for the inversion
    fine = np.linspace(0.0, 1.0, 4001)
    print("eta 1", flush=True)
    p1 = returns(scatter_counts(1.0, rng), fine)
    grid_c = np.linspace(0.0, 1.0, N_C)
    target = np.interp(grid_c, fine, p1)

    etas = 1.0 + (ETA_MAX - 1.0) * np.linspace(0.0, 1.0, N_ETA) ** 2
    table = np.ones((N_ETA, N_C))
    for i, eta in enumerate(etas):
        if i == 0:
            continue
        print(f"eta {eta:.4f}", flush=True)
        p = returns(scatter_counts(eta, rng), fine)
        # c' where the slab with the boundary returns the index-matched return
        # of C (the returns grow with the color)
        cp = np.interp(target, p, fine)
        valid = [j for j, c in enumerate(grid_c) if 0.0 < c <= C_MAX_FIT and 0.0 < cp[j] < 1.0]
        for j in valid:
            # c' = C / (T + C (1 - T))  ->  T = C (1 - c') / (c' (1 - C))
            c = grid_c[j]
            table[i, j] = c * (1.0 - cp[j]) / (cp[j] * (1.0 - c))
        # C = 0: the limit of the neighbours (T is smooth there). Above
        # C_MAX_FIT the inversion is ill-conditioned (c' is close to 1 whatever
        # T is, and the walks lost at SSS_MAX_BOUNCES make the return of C
        # unreachable at high eta): T stays at its last value.
        table[i, 0] = 2.0 * table[i, 1] - table[i, 2]
        table[i, valid[-1] + 1:] = table[i, valid[-1]]

    lines = [BEGIN,
             "//",
             "// The effective transmittance T[eta][C] of the boundary of the walk (see",
             "// SSS_BoundaryColor() and the generator for the definitions and the grids)",
             f"#define SSS_BOUNDARY_N_C {N_C}",
             f"#define SSS_BOUNDARY_N_ETA {N_ETA}",
             f"#define SSS_BOUNDARY_ETA_MAX {ETA_MAX:.1f}f",
             "",
             f"__constant float SSS_BoundaryTable[{N_ETA} * {N_C}] = {{"]
    def literal(v):
        s = f"{v:.6g}"
        return s + ("f" if ("." in s or "e" in s) else ".f")

    for i in range(N_ETA):
        vals = [literal(v) for v in table[i]]
        for k in range(0, N_C, 8):
            sep = "," if (i < N_ETA - 1 or k + 8 < N_C) else ""
            lines.append("\t" + ", ".join(vals[k:k + 8]) + sep)
    lines.append("};")
    lines.append(END)
    block = "\n".join(lines)

    with open(OUTPUT, "r", newline="") as f:
        src = f.read()
    pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)
    if not pattern.search(src):
        sys.exit(f"the GENERATED markers are missing in {OUTPUT}")
    nl = "\r\n" if "\r\n" in src else "\n"
    src = pattern.sub(lambda m: block.replace("\n", nl), src)
    with open(OUTPUT, "w", newline="") as f:
        f.write(src)
    print(f"written {OUTPUT}")


if __name__ == "__main__":
    main()
